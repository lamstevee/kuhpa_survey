// 직업코드 → 직업정보 매핑
export const JOB_INFO_MAP: Record<string, JobInfo> = Object.fromEntries(
  SAMPLE_JOBS.map((j) => [j.code, j])
);

// 직업명 → 직업코드 매핑
export const JOB_NAME_TO_INFO_CODE: Record<string, string> = Object.fromEntries(
  SAMPLE_JOBS.map((j) => [j.name, j.code])
);

function normalizeJobName(name: string): string {
  return name.replace(/[\s·()]/g, '');
}

export function getJobInfo(nameOrCode: string): JobInfo | null {
  if (JOB_INFO_MAP[nameOrCode]) return JOB_INFO_MAP[nameOrCode];

  const code = JOB_NAME_TO_INFO_CODE[nameOrCode];
  if (code && JOB_INFO_MAP[code]) return JOB_INFO_MAP[code];

  // 공백·기호를 무시한 정규화 매칭
  const normalized = normalizeJobName(nameOrCode);
  for (const j of SAMPLE_JOBS) {
    const n = normalizeJobName(j.name);
    if (n === normalized || n.includes(normalized) || normalized.includes(n)) return j;
  }

  return null;
}

export function getJobSummary(nameOrCode: string): string {
  return getJobInfo(nameOrCode)?.summary || '해당 직무에 대한 설명이 없습니다.';
}

export function getJobSalary(nameOrCode: string): string {
  return getJobInfo(nameOrCode)?.salaryInfo || '';
}
